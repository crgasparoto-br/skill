"""Offline rootless check dispatch under the controller's exclusive flock.

Internal-only adapter. The trusted caller supplies the job identity and a
snapshot generated by the pinned exporter. No OAuth, GitHub tokens or writes.
"""
from __future__ import annotations

import os
from pathlib import Path

from check_evidence import CheckEvidenceStore
from controller_lock import controller_lock
from verified_check_runner import run_and_record_checks


def dispatch_locked_checks(*, database_path: str, lock_path: str,
                           job_id: str, actor: str, snapshot_dir: str):
    if os.geteuid() != 1004:
        raise PermissionError("dedicated worker required")
    if not Path(database_path).is_file():
        raise FileNotFoundError("job database missing")
    with controller_lock(lock_path):
        store = CheckEvidenceStore(database_path)
        job = store.jobs.read(job_id, actor)
        if job.status != "prepared":
            raise PermissionError("job not prepared")
        snapshot = Path(snapshot_dir)
        if (not snapshot.is_absolute() or snapshot.is_symlink()
                or not snapshot.is_dir()):
            raise PermissionError("invalid trusted snapshot")
        marker = snapshot / ".solverit-expected-sha"
        if marker.is_symlink() or not marker.is_file():
            raise PermissionError("missing pinned marker")
        if marker.read_text(encoding="ascii").strip() != job.base_sha:
            raise PermissionError("snapshot SHA mismatch")
        return run_and_record_checks(
            database_path=database_path, job_id=job_id,
            actor=actor, snapshot_dir=str(snapshot),
        )
